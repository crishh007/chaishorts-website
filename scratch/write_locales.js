function run() {
  console.log("Writing localization JSON files manually...");
  
  for (const lang of TARGET_LANGS) {
    const destDir = path.join('src', 'locales', lang);
    if (!fs.existsSync(destDir)) {
      fs.mkdirSync(destDir, { recursive: true });
    }
    
    for (const key of Object.keys(locales)) {
      const data = locales[key][lang];
      if (data) {
        const destPath = path.join(destDir, `${key}.json`);
        fs.writeFileSync(destPath, JSON.stringify(data, null, 2), 'utf-8');
        console.log(`Wrote: ${destPath}`);
      }
    }
  }
  
  console.log("Done!");
}

run();
